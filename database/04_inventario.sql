CREATE SCHEMA IF NOT EXISTS inventario;

CREATE TABLE IF NOT EXISTS inventario.stock (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_id             BIGINT        NOT NULL REFERENCES nucleo.local(id) ON DELETE RESTRICT,
    variante_id          BIGINT        NULL REFERENCES catalogo.variante_producto(id) ON DELETE RESTRICT,
    material_id          BIGINT        NULL REFERENCES catalogo.material(id) ON DELETE RESTRICT,
    cantidad_disponible  NUMERIC(12, 4) NOT NULL DEFAULT 0,
    cantidad_reservada   NUMERIC(12, 4) NOT NULL DEFAULT 0,
    activo               BOOLEAN       NOT NULL DEFAULT true,
    creado_en            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- XOR: exactamente uno entre material y variante
    CONSTRAINT inventory_stock_excluyente CHECK (
        (material_id IS NOT NULL AND variante_id IS NULL)
        OR (material_id IS NULL AND variante_id IS NOT NULL)
    ),
    CONSTRAINT inventory_stock_disponible_ck CHECK (cantidad_disponible >= 0),
    CONSTRAINT inventory_stock_reservada_ck CHECK (cantidad_reservada >= 0)
);
-- Una sola fila de saldo por clave (material o variante) en cada local
CREATE UNIQUE INDEX IF NOT EXISTS inventory_stock_material_uk
    ON inventario.stock (local_id, material_id) WHERE material_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS inventory_stock_variante_uk
    ON inventario.stock (local_id, variante_id) WHERE variante_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS inventario.lote (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id       BIGINT        NOT NULL REFERENCES catalogo.material(id) ON DELETE RESTRICT,
    local_id          BIGINT        NOT NULL REFERENCES nucleo.local(id) ON DELETE RESTRICT,
    numero_lote       VARCHAR(30)   NOT NULL,
    longitud_inicial  NUMERIC(12, 4) NULL,
    longitud_actual   NUMERIC(12, 4) NULL,
    costo_unitario    NUMERIC(14, 2) NOT NULL,
    moneda            VARCHAR(3)    NOT NULL DEFAULT 'USD',
    fecha_ingreso     DATE          NOT NULL DEFAULT CURRENT_DATE,
    fecha_vencimiento DATE          NULL,
    activo            BOOLEAN       NOT NULL DEFAULT true,
    creado_en         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT inventory_lote_numero_uk UNIQUE (numero_lote),
    CONSTRAINT inventory_lote_costo_ck CHECK (costo_unitario >= 0),
    CONSTRAINT inventory_lote_moneda_ck CHECK (moneda IN ('USD', 'VES'))
);
CREATE INDEX IF NOT EXISTS inventory_lote_loc_mat_idx
    ON inventario.lote (local_id, material_id);

CREATE TABLE IF NOT EXISTS inventario.movimiento_stock (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo         VARCHAR(20)   NOT NULL DEFAULT 'ENTRADA',
    local_id     BIGINT        NOT NULL REFERENCES nucleo.local(id) ON DELETE RESTRICT,
    cantidad     NUMERIC(12, 4) NOT NULL,
    referencia   VARCHAR(100)  NOT NULL DEFAULT '',
    activo       BOOLEAN       NOT NULL DEFAULT true,
    creado_en    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT inventory_movimiento_cantidad_ck CHECK (cantidad > 0),
    CONSTRAINT inventory_movimiento_tipo_ck
        CHECK (tipo IN ('ENTRADA', 'SALIDA', 'TRANSFERENCIA'))
);
CREATE INDEX IF NOT EXISTS inventory_mov_loc_fecha_idx
    ON inventario.movimiento_stock (local_id, creado_en DESC);

CREATE TABLE IF NOT EXISTS inventario.guia_transferencia (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_guia      VARCHAR(30) NOT NULL,
    local_origen_id  BIGINT      NOT NULL REFERENCES nucleo.local(id) ON DELETE RESTRICT,
    local_destino_id BIGINT      NOT NULL REFERENCES nucleo.local(id) ON DELETE RESTRICT,
    estado           VARCHAR(20) NOT NULL DEFAULT 'BORRADOR',
    activo           BOOLEAN     NOT NULL DEFAULT true,
    creado_en        TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT inventory_guia_codigo_uk UNIQUE (codigo_guia),
    CONSTRAINT inventory_guia_locales_ck CHECK (local_origen_id <> local_destino_id),
    CONSTRAINT inventory_guia_estado_ck
        CHECK (estado IN ('BORRADOR', 'EN_TRANSITO', 'RECIBIDA', 'RECHAZADA'))
);

CREATE TABLE IF NOT EXISTS inventario.linea_guia_transferencia (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guia_id          BIGINT        NOT NULL REFERENCES inventario.guia_transferencia(id) ON DELETE CASCADE,
    lote_id          BIGINT        NULL REFERENCES inventario.lote(id) ON DELETE RESTRICT,
    variante_id      BIGINT        NULL REFERENCES catalogo.variante_producto(id) ON DELETE RESTRICT,
    cantidad         NUMERIC(12, 4) NOT NULL,
    unidad_medida_id BIGINT        NOT NULL REFERENCES catalogo.unidad_medida(id) ON DELETE RESTRICT,
    estado           VARCHAR(20)   NOT NULL DEFAULT 'PENDIENTE',
    activo           BOOLEAN       NOT NULL DEFAULT true,
    creado_en        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- XOR: la línea transporta un lote o una variante, nunca ambos
    CONSTRAINT inventory_linea_excluyente CHECK (
        (lote_id IS NOT NULL AND variante_id IS NULL)
        OR (lote_id IS NULL AND variante_id IS NOT NULL)
    ),
    CONSTRAINT inventory_linea_cantidad_ck CHECK (cantidad > 0),
    CONSTRAINT inventory_linea_estado_ck
        CHECK (estado IN ('PENDIENTE', 'DESPACHADA', 'RECIBIDA', 'DESVIADA'))
);
CREATE INDEX IF NOT EXISTS inventory_linea_guia_idx
    ON inventario.linea_guia_transferencia (guia_id);

CREATE TABLE IF NOT EXISTS inventario.nivel_minimo (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_id               BIGINT        NOT NULL REFERENCES nucleo.local(id) ON DELETE RESTRICT,
    producto_id            BIGINT        NULL REFERENCES catalogo.producto(id) ON DELETE RESTRICT,
    material_id            BIGINT        NULL REFERENCES catalogo.material(id) ON DELETE RESTRICT,
    cantidad_minima_alerta NUMERIC(12, 4) NOT NULL,
    activo                 BOOLEAN       NOT NULL DEFAULT true,
    creado_en              TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- XOR: la alerta apunta a un material o a un producto
    CONSTRAINT inventory_nivel_excluyente CHECK (
        (material_id IS NOT NULL AND producto_id IS NULL)
        OR (material_id IS NULL AND producto_id IS NOT NULL)
    ),
    CONSTRAINT inventory_nivel_cantidad_ck CHECK (cantidad_minima_alerta >= 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS inventory_nivel_material_uk
    ON inventario.nivel_minimo (local_id, material_id) WHERE material_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS inventory_nivel_producto_uk
    ON inventario.nivel_minimo (local_id, producto_id) WHERE producto_id IS NOT NULL;
