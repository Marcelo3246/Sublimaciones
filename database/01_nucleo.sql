CREATE SCHEMA IF NOT EXISTS nucleo;

CREATE TABLE IF NOT EXISTS nucleo.local (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           VARCHAR(10)  NOT NULL,
    nombre           VARCHAR(100) NOT NULL,
    direccion        VARCHAR(255) NOT NULL DEFAULT '',
    telefono         VARCHAR(50)  NOT NULL DEFAULT '',
    persona_contacto VARCHAR(100) NOT NULL DEFAULT '',
    activo           BOOLEAN      NOT NULL DEFAULT true,
    creado_en        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_en   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT locales_codigo_uk UNIQUE (codigo)
);

CREATE TABLE IF NOT EXISTS nucleo.usuario (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password        VARCHAR(128) NOT NULL,
    last_login      TIMESTAMPTZ,
    is_superuser    BOOLEAN      NOT NULL DEFAULT false,
    nombre_usuario  VARCHAR(150) NOT NULL,
    correo          VARCHAR(254) NOT NULL,
    nombre          VARCHAR(150) NOT NULL DEFAULT '',
    apellido        VARCHAR(150) NOT NULL DEFAULT '',
    rol             VARCHAR(20)  NOT NULL DEFAULT 'vendedor',
    es_global       BOOLEAN      NOT NULL DEFAULT false,
    activo          BOOLEAN      NOT NULL DEFAULT true,
    local_id        BIGINT       NULL REFERENCES nucleo.local(id) ON DELETE SET NULL,
    creado_en       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_en  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT usuarios_nombre_usuario_uk UNIQUE (nombre_usuario),
    CONSTRAINT usuarios_correo_uk UNIQUE (correo)
);

CREATE TABLE IF NOT EXISTS nucleo.tasa_cambio (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_vigencia    DATE         NOT NULL DEFAULT CURRENT_DATE,
    dolares_a_bs      NUMERIC(14, 4) NOT NULL CHECK (dolares_a_bs > 0),
    registrado_por_id BIGINT       NULL REFERENCES nucleo.usuario(id) ON DELETE SET NULL,
    activo            BOOLEAN      NOT NULL DEFAULT true,
    creado_en         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_en    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS core_tasa_vigencia_idx
    ON nucleo.tasa_cambio (fecha_vigencia DESC, creado_en DESC);

CREATE TABLE IF NOT EXISTS nucleo.contador_correlativo (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_comprobante VARCHAR(50)  NOT NULL,
    prefijo          VARCHAR(10)  NOT NULL DEFAULT '',
    numero_actual    INTEGER      NOT NULL DEFAULT 0 CHECK (numero_actual >= 0),
    local_id         BIGINT       NOT NULL REFERENCES nucleo.local(id) ON DELETE RESTRICT,
    anio             SMALLINT     NOT NULL,
    activo           BOOLEAN      NOT NULL DEFAULT true,
    creado_en        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_en   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT core_contador_correlativo_uk UNIQUE (tipo_comprobante, local_id, anio)
);
