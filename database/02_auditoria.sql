CREATE SCHEMA IF NOT EXISTS auditoria;

CREATE TABLE IF NOT EXISTS auditoria.bitacora_accion (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT       NULL REFERENCES nucleo.usuario(id) ON DELETE SET NULL,
    local_id       BIGINT       NULL REFERENCES nucleo.local(id) ON DELETE SET NULL,
    modulo         VARCHAR(50)  NOT NULL DEFAULT '',
    accion         VARCHAR(30)  NOT NULL,
    entidad        VARCHAR(100) NOT NULL,
    entidad_id     BIGINT       NULL,
    datos_antes    JSONB        NULL,
    datos_despues  JSONB        NULL,
    ip_origen      INET         NULL,
    creado_en      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS audit_accion_usr_idx
    ON auditoria.bitacora_accion (usuario_id, creado_en DESC);

CREATE INDEX IF NOT EXISTS audit_accion_ent_idx
    ON auditoria.bitacora_accion (modulo, entidad, entidad_id);

CREATE TABLE IF NOT EXISTS auditoria.bitacora_stock (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_movimiento  VARCHAR(30)    NOT NULL,
    lote_id          BIGINT         NULL,
    producto_id      BIGINT         NULL,
    cantidad         NUMERIC(12, 4) NOT NULL,
    codigo_um        VARCHAR(10)    NOT NULL DEFAULT '',
    local_origen_id  BIGINT         NULL REFERENCES nucleo.local(id) ON DELETE RESTRICT,
    local_destino_id BIGINT         NULL REFERENCES nucleo.local(id) ON DELETE RESTRICT,
    usuario_id       BIGINT         NOT NULL REFERENCES nucleo.usuario(id) ON DELETE RESTRICT,
    motivo           VARCHAR(255)   NOT NULL DEFAULT '',
    creado_en        TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS audit_stk_loc_orig_idx
    ON auditoria.bitacora_stock (local_origen_id, creado_en DESC);

CREATE INDEX IF NOT EXISTS audit_stk_prod_idx
    ON auditoria.bitacora_stock (producto_id, creado_en DESC);
