-- =============================================================================
-- 08_precios.sql
-- DDL para las tablas del esquema `precios`:
-- Matriz de precios, historial de cambios de precio y parámetros de la
-- fórmula con vigencia por fechas (RF-44 a RF-47).
-- El precio final (base × margen × (1 + iva)) se calcula en servicios y no
-- se persiste.
-- Requiere: 01_nucleo.sql y 03_catalogo.sql.
--
-- Referencias:
--   docs/ddl/06b.8-precios.md
--   docs/modelo-datos/06.8-precios.md
--   docs/03-requerimientos-del-sistema.md (RF-44 a RF-47)
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS precios;

CREATE TABLE IF NOT EXISTS precios.item_matriz_precios (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id              BIGINT        NULL REFERENCES catalogo.producto(id) ON DELETE RESTRICT,
    variante_id              BIGINT        NULL REFERENCES catalogo.variante_producto(id) ON DELETE RESTRICT,
    servicio_id              BIGINT        NULL REFERENCES catalogo.servicio(id) ON DELETE RESTRICT,
    material_id              BIGINT        NULL REFERENCES catalogo.material(id) ON DELETE RESTRICT,
    unidad_medida_id         BIGINT        NULL REFERENCES catalogo.unidad_medida(id) ON DELETE RESTRICT,
    medida_cantidad          NUMERIC(12, 4) NULL,
    unidad_medida_medida_id  BIGINT        NULL REFERENCES catalogo.unidad_medida(id) ON DELETE RESTRICT,
    precio_base              NUMERIC(14, 2) NOT NULL,
    moneda                   VARCHAR(3)    NOT NULL DEFAULT 'USD',
    porcentaje_margen        NUMERIC(5, 4) NOT NULL,
    porcentaje_iva           NUMERIC(5, 4) NOT NULL,
    activo                   BOOLEAN       NOT NULL DEFAULT true,
    creado_en                TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- Exactamente un destino: producto, variante o servicio
    CONSTRAINT pricing_item_destino_excluyente CHECK (
        (producto_id IS NOT NULL AND variante_id IS NULL AND servicio_id IS NULL)
        OR (producto_id IS NULL AND variante_id IS NOT NULL AND servicio_id IS NULL)
        OR (producto_id IS NULL AND variante_id IS NULL AND servicio_id IS NOT NULL)
    ),
    -- Medida y su unidad van juntas (ambas o ninguna)
    CONSTRAINT pricing_item_medida_um_ck CHECK (
        (medida_cantidad IS NULL AND unidad_medida_medida_id IS NULL)
        OR (medida_cantidad IS NOT NULL AND unidad_medida_medida_id IS NOT NULL)
    ),
    CONSTRAINT pricing_item_precio_base_ck CHECK (precio_base >= 0),
    CONSTRAINT pricing_item_margen_ck CHECK (porcentaje_margen > 0),
    CONSTRAINT pricing_item_iva_ck CHECK (porcentaje_iva >= 0),
    CONSTRAINT pricing_item_moneda_ck CHECK (moneda IN ('USD', 'VES'))
);
CREATE INDEX IF NOT EXISTS pricing_item_producto_idx ON precios.item_matriz_precios (producto_id);
CREATE INDEX IF NOT EXISTS pricing_item_variante_idx ON precios.item_matriz_precios (variante_id);
CREATE INDEX IF NOT EXISTS pricing_item_servicio_idx ON precios.item_matriz_precios (servicio_id);

-- Append-only: cada cambio del precio base conserva valor anterior y usuario (RF-46)
CREATE TABLE IF NOT EXISTS precios.historial_cambio_precio (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_matriz_id  BIGINT        NOT NULL REFERENCES precios.item_matriz_precios(id) ON DELETE RESTRICT,
    precio_anterior NUMERIC(14, 2) NOT NULL,
    precio_nuevo    NUMERIC(14, 2) NOT NULL,
    usuario_id      BIGINT        NOT NULL REFERENCES nucleo.usuario(id) ON DELETE RESTRICT,
    cambiado_en     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    activo          BOOLEAN       NOT NULL DEFAULT true,
    creado_en       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en  TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS pricing_historial_item_idx
    ON precios.historial_cambio_precio (item_matriz_id, cambiado_en DESC);

-- Fórmula parametrizable por vigencia (RF-45)
CREATE TABLE IF NOT EXISTS precios.parametro_formula (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    porcentaje_margen NUMERIC(5, 4) NOT NULL,
    porcentaje_iva    NUMERIC(5, 4) NOT NULL,
    fecha_desde       DATE          NOT NULL,
    fecha_hasta       DATE          NULL,  -- NULL = vigente hasta que exista el siguiente
    registrado_por_id BIGINT        NOT NULL REFERENCES nucleo.usuario(id) ON DELETE RESTRICT,
    activo            BOOLEAN       NOT NULL DEFAULT true,
    creado_en         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT pricing_parametro_formula_uk UNIQUE (fecha_desde),
    CONSTRAINT pricing_parametro_margen_ck CHECK (porcentaje_margen > 0),
    CONSTRAINT pricing_parametro_iva_ck CHECK (porcentaje_iva >= 0),
    CONSTRAINT pricing_parametro_vigencia_ck CHECK (
        fecha_hasta IS NULL OR fecha_hasta > fecha_desde
    )
);
