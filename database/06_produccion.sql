CREATE SCHEMA IF NOT EXISTS produccion;

CREATE TABLE IF NOT EXISTS produccion.maquina (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo             VARCHAR(30)   NOT NULL,
    nombre             VARCHAR(100)  NOT NULL,
    local_id           BIGINT        NOT NULL REFERENCES nucleo.local(id) ON DELETE RESTRICT,
    tipo               VARCHAR(20)   NOT NULL DEFAULT 'OTRO',
    estado             VARCHAR(20)   NOT NULL DEFAULT 'OPERATIVA',
    horas_operativas   NUMERIC(10, 2) NOT NULL DEFAULT 0,
    activo             BOOLEAN       NOT NULL DEFAULT true,
    creado_en          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT production_maquina_codigo_uk UNIQUE (codigo),
    CONSTRAINT production_maquina_tipo_ck
        CHECK (tipo IN ('IMPRESORA', 'PLANCHA', 'CORTADORA', 'OTRO')),
    CONSTRAINT production_maquina_estado_ck
        CHECK (estado IN ('OPERATIVA', 'MANTENIMIENTO', 'INACTIVA')),
    CONSTRAINT production_maquina_horas_ck CHECK (horas_operativas >= 0)
);
CREATE INDEX IF NOT EXISTS production_maquina_local_idx
    ON produccion.maquina (local_id);

CREATE TABLE IF NOT EXISTS produccion.orden_produccion (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo            VARCHAR(30)   NOT NULL,
    pedido_venta_id   BIGINT        NULL,   -- referencia débil a ventas.pedido_venta
    variante_id       BIGINT        NOT NULL REFERENCES catalogo.variante_producto(id) ON DELETE RESTRICT,
    cantidad          NUMERIC(12, 4) NOT NULL,
    local_origen_id   BIGINT        NOT NULL REFERENCES nucleo.local(id) ON DELETE RESTRICT,
    estado            VARCHAR(20)   NOT NULL DEFAULT 'CREADA',
    fecha_limite      DATE          NULL,
    costo_materiales  NUMERIC(14, 2) NULL,
    costo_horas       NUMERIC(14, 2) NULL,
    costo_total       NUMERIC(14, 2) NULL,
    moneda            VARCHAR(3)    NOT NULL DEFAULT 'USD',
    fecha_cierre      TIMESTAMPTZ   NULL,
    activo            BOOLEAN       NOT NULL DEFAULT true,
    creado_en         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT production_orden_codigo_uk UNIQUE (codigo),
    CONSTRAINT production_oc_cantidad_ck CHECK (cantidad > 0),
    CONSTRAINT production_oc_estado_ck
        CHECK (estado IN ('CREADA', 'EN_PRODUCCION', 'TERMINADA', 'ANULADA')),
    CONSTRAINT production_oc_moneda_ck CHECK (moneda IN ('USD', 'VES')),
    -- RF-35: orden terminada exige costo total y fecha de cierre
    CONSTRAINT production_oc_cierre_ck
        CHECK (estado <> 'TERMINADA' OR (costo_total IS NOT NULL AND fecha_cierre IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS production_oc_estado_idx
    ON produccion.orden_produccion (estado, local_origen_id);
CREATE INDEX IF NOT EXISTS production_oc_pedido_idx
    ON produccion.orden_produccion (pedido_venta_id);

-- Ruta multi-local: pasos encadenados por local (RF-31)
CREATE TABLE IF NOT EXISTS produccion.paso_produccion (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_produccion_id BIGINT        NOT NULL REFERENCES produccion.orden_produccion(id) ON DELETE CASCADE,
    orden_paso          SMALLINT      NOT NULL,
    tipo                VARCHAR(20)   NOT NULL DEFAULT 'IMPRESION',
    local_id            BIGINT        NOT NULL REFERENCES nucleo.local(id) ON DELETE RESTRICT,
    trabajador_id       BIGINT        NULL REFERENCES rrhh.trabajador(id) ON DELETE RESTRICT,
    descripcion_tarea   VARCHAR(300)  NOT NULL DEFAULT '',
    estado              VARCHAR(20)   NOT NULL DEFAULT 'PENDIENTE',
    iniciado_en         TIMESTAMPTZ   NULL,
    terminado_en        TIMESTAMPTZ   NULL,
    activo              BOOLEAN       NOT NULL DEFAULT true,
    creado_en           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT production_paso_orden_uk UNIQUE (orden_produccion_id, orden_paso),
    CONSTRAINT production_paso_orden_ck CHECK (orden_paso > 0),
    CONSTRAINT production_paso_estado_ck
        CHECK (estado IN ('PENDIENTE', 'EN_PROCESO', 'TERMINADO')),
    CONSTRAINT production_paso_fechas_ck
        CHECK (iniciado_en IS NULL OR terminado_en IS NULL OR iniciado_en <= terminado_en)
);
CREATE INDEX IF NOT EXISTS production_paso_loc_est_idx
    ON produccion.paso_produccion (local_id, estado);

-- Consumo por medición sobre lote o stock, uso o desperdicio (RF-32, RF-34)
CREATE TABLE IF NOT EXISTS produccion.consumo_material (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paso_id             BIGINT        NOT NULL REFERENCES produccion.paso_produccion(id) ON DELETE CASCADE,
    lote_id             BIGINT        NULL REFERENCES inventario.lote(id) ON DELETE RESTRICT,
    stock_id            BIGINT        NULL REFERENCES inventario.stock(id) ON DELETE RESTRICT,
    cantidad_consumida  NUMERIC(12, 4) NOT NULL,
    unidad_medida_id    BIGINT        NOT NULL REFERENCES catalogo.unidad_medida(id) ON DELETE RESTRICT,
    tipo                VARCHAR(20)   NOT NULL DEFAULT 'USO',
    motivo_desperdicio  VARCHAR(200)  NOT NULL DEFAULT '',
    movimiento_stock_id BIGINT        NULL,  -- referencia débil a inventario.movimiento_stock
    activo              BOOLEAN       NOT NULL DEFAULT true,
    creado_en           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT production_consumo_cantidad_ck CHECK (cantidad_consumida > 0),
    CONSTRAINT production_consumo_tipo_ck CHECK (tipo IN ('USO', 'DESPERDICIO')),
    CONSTRAINT production_consumo_excluyente CHECK (
        (lote_id IS NOT NULL AND stock_id IS NULL)
        OR (lote_id IS NULL AND stock_id IS NOT NULL)
    ),
    CONSTRAINT production_consumo_motivo_ck
        CHECK (tipo <> 'DESPERDICIO' OR motivo_desperdicio <> '')
);
CREATE INDEX IF NOT EXISTS production_consumo_paso_idx
    ON produccion.consumo_material (paso_id);

CREATE TABLE IF NOT EXISTS produccion.operacion_maquina (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paso_id                BIGINT        NOT NULL REFERENCES produccion.paso_produccion(id) ON DELETE CASCADE,
    maquina_id             BIGINT        NOT NULL REFERENCES produccion.maquina(id) ON DELETE RESTRICT,
    operador_trabajador_id BIGINT        NOT NULL REFERENCES rrhh.trabajador(id) ON DELETE RESTRICT,
    duracion_minutos       NUMERIC(8, 2) NOT NULL,
    resultado              VARCHAR(20)   NOT NULL DEFAULT 'COMPLETADO',
    nota                   VARCHAR(300)  NOT NULL DEFAULT '',
    activo                 BOOLEAN       NOT NULL DEFAULT true,
    creado_en              TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT production_op_duracion_ck CHECK (duracion_minutos >= 0),
    CONSTRAINT production_op_resultado_ck
        CHECK (resultado IN ('COMPLETADO', 'DEFECTUOSO', 'PARCIAL'))
);
CREATE INDEX IF NOT EXISTS production_op_maquina_idx
    ON produccion.operacion_maquina (maquina_id, creado_en DESC);
